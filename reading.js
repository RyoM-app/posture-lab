// 被験者・回ごとに順番に変える：番号 ＝ (被験者の番号 − 1) × 3 ＋ (回番号 − 1) を 6 で割った余り。
// 1人3回（固定2回・手持ち1回）なら、P01 は 1〜3本目、P02 は 4〜6本目、P03 は 1〜3本目 … になる
export function chooseReadingText(subjectId, run) {
  const m = /^P(\d+)$/.exec(subjectId || ''), n = m ? Number(m[1]) : 1, r = Number(run) || 1;
  const index = (((n - 1) * 3 + (r - 1)) % READING_TEXTS.length + READING_TEXTS.length) % READING_TEXTS.length;
  return { index, ...READING_TEXTS[index], rule: '(subjectNumber - 1) * 3 + (run - 1) mod 6' };
}
